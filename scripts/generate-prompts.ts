/**
 * Writes `src/core/prompt/bundled.ts` from `prompts/*.md`, or with `--check`
 * fails when it is stale. The bundle then carries the default prompts as
 * strings, with no file lookup relative to the bundle at run time.
 *
 * Usage: tsx scripts/generate-prompts.ts [--check]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

/** The generated module. */
export const OUTPUT = join(ROOT, "src", "core", "prompt", "bundled.ts");

/**
 * Renders the module text from the Markdown sources.
 *
 * @returns TypeScript source
 */
export function renderPrompts(): string {
  const read = (name: string) =>
    readFileSync(join(ROOT, "prompts", `${name}.md`), "utf8").replace(/\n$/, "");
  return [
    "// Generated by scripts/generate-prompts.ts from prompts/*.md. Do not edit.",
    "",
    "/** prompts/system.md */",
    `export const BUNDLED_SYSTEM = ${JSON.stringify(read("system"))};`,
    "",
    "/** prompts/persona.md */",
    `export const BUNDLED_PERSONA = ${JSON.stringify(read("persona"))};`,
    "",
  ].join("\n");
}

function main(): void {
  const expected = renderPrompts();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUTPUT, "utf8");
    } catch {
      // Missing counts as stale.
    }
    if (current !== expected) {
      console.error("check-prompts: src/core/prompt/bundled.ts is stale; run pnpm prompts");
      process.exit(1);
    }
    console.log("check-prompts: src/core/prompt/bundled.ts is current");
    return;
  }
  writeFileSync(OUTPUT, expected);
  console.log(`Wrote ${OUTPUT}`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) main();
