/**
 * `mode: adopt` (CONVERSION-PLAN §9.5, PD-9) and its write pacing (§5.7):
 * Phase 5 acceptance criterion 5, with a mocked release API and a fake clock.
 */
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterAll, describe, expect, it } from "vitest";
import { loadConfig } from "../../src/config/load";
import { ReleaseRayError } from "../../src/core/errors";
import { createGit } from "../../src/core/range/git";
import { findMarkedBlocks } from "../../src/core/state/marker";
import { planSink } from "../../src/core/state/planner";
import { adopt, ADOPT_PACING, formatTime } from "../../src/modes/adopt";
import type { ModeResult } from "../../src/modes/types";
import { fakeReleases } from "../helpers/fake-release";
import { createTestRepo, type TestRepo } from "../helpers/git-repo";

const HOUR = 60 * 60 * 1000;
const START = Date.parse("2026-11-23T10:00:00Z");

/** A body the way the hosted App wrote it: no markers. */
const hostedBody = (tag: string) =>
  `## What's Changed\n\n### ✨ Features\n\n- **Export to CSV** for ${tag} (#2)\n\n---\n\n_Generated by ReleaseRay_`;

const repos: TestRepo[] = [];
const dirs: string[] = [];
afterAll(() => {
  for (const r of repos) r.remove();
  for (const d of dirs) rmSync(d, { recursive: true, force: true });
});

/** A repository with one commit and the given tags on it. */
function repoWithTags(tags: readonly string[]): TestRepo {
  const repo = createTestRepo();
  repos.push(repo);
  const sha = repo.commit("chore: initial commit", "2026-01-10");
  execFileSync("git", ["update-ref", "--stdin"], {
    cwd: repo.dir,
    input: tags.map((t) => `create refs/tags/${t} ${sha}\n`).join(""),
  });
  return repo;
}

function config(overrides: Record<string, unknown> = {}) {
  const dir = mkdtempSync(join(tmpdir(), "releaseray-adopt-config-"));
  dirs.push(dir);
  return loadConfig({ workspace: dir, overrides });
}

/** A fake clock; each write also takes `latencyMs` of it, as a real request does. */
function clock(latencyMs = 0) {
  let t = START;
  return {
    now: () => t,
    sleep: async (ms: number) => {
      t += ms;
    },
    set: (ms: number) => {
      t = ms;
    },
    advance: (ms: number) => {
      t += ms;
    },
    latencyMs,
  };
}

/** Releases whose writes are timed on the fake clock. */
function timedReleases(
  c: ReturnType<typeof clock>,
  initial: Parameters<typeof fakeReleases>[0]
): ReturnType<typeof fakeReleases> & { times: number[] } {
  const fake = fakeReleases(initial);
  const times: number[] = [];
  const update = fake.api.updateBody.bind(fake.api);
  fake.api.updateBody = async (id, body) => {
    times.push(c.now());
    c.advance(c.latencyMs);
    return update(id, body);
  };
  return { ...fake, times };
}

function deps(
  repo: TestRepo,
  c: ReturnType<typeof clock>,
  releases: ReturnType<typeof fakeReleases>
) {
  return {
    git: createGit(repo.dir),
    release: releases.api,
    persisted: { release: releases.api, workspace: repo.dir },
    now: c.now,
    sleep: c.sleep,
  };
}

/** The most writes in any 60-minute window starting at a write. */
function busiestHour(times: readonly number[]): number {
  const sorted = [...times].sort((a, b) => a - b);
  let most = 0;
  for (let i = 0, j = 0; i < sorted.length; i++) {
    while (j < sorted.length && sorted[j] < sorted[i] + HOUR) j++;
    most = Math.max(most, j - i);
  }
  return most;
}

function failure(run: () => Promise<ModeResult>): Promise<ReleaseRayError> {
  return run().then(
    () => {
      throw new Error("expected a failure");
    },
    (error: unknown) => {
      expect(error).toBeInstanceOf(ReleaseRayError);
      return error as ReleaseRayError;
    }
  );
}

describe("5.5 adopt pacing", () => {
  it("spaces 450 planned writes 7.2 s apart, stops at 400 with the next safe start, and never exceeds 500 an hour", async () => {
    const tags = Array.from({ length: 450 }, (_, i) => `v1.0.${i}`);
    const repo = repoWithTags(tags);
    const c = clock(350);
    const releases = timedReleases(
      c,
      tags.map((tag) => ({ tag, body: hostedBody(tag) }))
    );
    const request = { workspace: repo.dir, to: "", allTags: true };

    const first = await adopt(request, config(), deps(repo, c, releases));
    expect(releases.reads()).toBe(450);
    expect(releases.times).toHaveLength(ADOPT_PACING.maxWrites);
    const gaps = releases.times.slice(1).map((t, i) => t - releases.times[i]);
    expect(new Set(gaps)).toEqual(new Set([7200]));
    // Newest first: v1.0.449 down to v1.0.50 were written; v1.0.49 is next.
    expect(releases.releases.get("v1.0.449")!.body).toContain("gen=adopted");
    expect(releases.releases.get("v1.0.49")!.body).toBe(hostedBody("v1.0.49"));
    const nextStart = START + HOUR;
    expect(first.warnings).toHaveLength(1);
    expect(first.warnings[0]).toContain("Stopped after 400 release writes");
    expect(first.warnings[0]).toContain("50 releases still need adopting, starting with v1.0.49");
    expect(first.warnings[0]).toContain(`Next safe start: ${formatTime(nextStart)}`);
    expect(first.summary).toContain("400 adopted, 50 pending");
    expect(first.outputs).toMatchObject({ "release-changed": "true", "llm-calls": "0" });

    // Resuming at the time the notice names adopts the rest and skips the adopted ones.
    c.set(nextStart);
    const second = await adopt(request, config(), deps(repo, c, releases));
    expect(second.warnings).toEqual([]);
    expect(releases.times).toHaveLength(450);
    expect(releases.times[400]).toBe(nextStart);
    // 50 planned writes: the 1-second spacing applies.
    expect(releases.times[401] - releases.times[400]).toBe(1000);
    expect([...releases.releases.values()].every((r) => r.body.includes("gen=adopted"))).toBe(true);
    expect(busiestHour(releases.times)).toBeLessThanOrEqual(500);
    // Even a resume at the cap's end would fit: 400 + 80 at most per hour.
    expect(ADOPT_PACING.maxWrites + ADOPT_PACING.burstWrites).toBeLessThanOrEqual(500);
  });

  it("spaces at most 80 planned writes 1 second apart", async () => {
    const tags = ["v1.0.0", "v1.1.0", "v1.2.0"];
    const repo = repoWithTags(tags);
    const c = clock(200);
    const releases = timedReleases(
      c,
      tags.map((tag) => ({ tag, body: hostedBody(tag) }))
    );
    const run = await adopt(
      { workspace: repo.dir, to: "", allTags: true },
      config(),
      deps(repo, c, releases)
    );
    expect(releases.times.map((t) => t - START)).toEqual([0, 1000, 2000]);
    expect(run.warnings).toEqual([]);
    expect(run.summary).toContain(
      `Next safe start for another bulk adopt: ${formatTime(START + HOUR)}`
    );
  });
});

describe("adopt", () => {
  it("wraps an unmarked body with gen=adopted, so the next plan is a no-op", async () => {
    const tags = ["v1.0.0", "v1.1.0", "v1.2.0", "v1.3.0", "v1.4.0"];
    const repo = repoWithTags(tags);
    const c = clock();
    const marked =
      "<!-- releaseray:begin v=1 key=v1.2.0 persona=engineer gen=0123456789abcdef out=0000000000000000 -->\n\nx\n\n<!-- releaseray:end key=v1.2.0 persona=engineer -->";
    const releases = timedReleases(c, [
      { tag: "v1.1.0", body: `\r\n${hostedBody("v1.1.0").replace(/\n/g, "\r\n")}\r\n\r\n` },
      { tag: "v1.2.0", body: marked },
      { tag: "v1.3.0", body: "  \n" },
      {
        tag: "v1.4.0",
        body: "Intro\n\n<!-- releaseray:begin v=1 key=v1.4.0 persona=customer gen=a out=b -->",
      },
    ]);
    const run = await adopt(
      { workspace: repo.dir, to: "", allTags: true },
      config(),
      deps(repo, c, releases)
    );
    expect(releases.times).toHaveLength(1);
    const body = releases.releases.get("v1.1.0")!.body;
    const [block] = findMarkedBlocks(body);
    expect(block.fields).toMatchObject({ key: "v1.1.0", persona: "engineer", gen: "adopted" });
    expect(block.inner).toBe(hostedBody("v1.1.0"));
    expect(body.startsWith("<!-- releaseray:begin")).toBe(true);
    const target = {
      sink: "github-release" as const,
      exists: true,
      text: body,
      mode: "section" as const,
      onHumanEdit: "skip" as const,
      createIfMissing: false,
    };
    const request = { key: "v1.1.0", persona: "engineer", gen: "fedcba9876543210", force: false };
    expect(planSink(target, request).action).toBe("noop");
    expect(planSink({ ...target, onHumanEdit: "overwrite" }, request).action).toBe("noop");

    expect(releases.releases.get("v1.2.0")!.body).toBe(marked);
    expect(releases.releases.get("v1.3.0")!.body).toBe("  \n");
    expect(run.warnings).toEqual([
      "The release body for v1.4.0 has ReleaseRay markers for another key or persona, or a broken marker; it was left unchanged",
    ]);
    for (const [tag, state] of [
      ["v1.0.0", "no release"],
      ["v1.1.0", "adopted"],
      ["v1.2.0", "already marked"],
      ["v1.3.0", "empty body"],
      ["v1.4.0", "skipped"],
    ]) {
      expect(run.summary).toContain(`| \`${tag}\` | ${state} |`);
    }

    // A second run writes nothing.
    const again = await adopt(
      { workspace: repo.dir, to: "v1.1.0", allTags: false },
      config(),
      deps(repo, c, releases)
    );
    expect(releases.times).toHaveLength(1);
    expect(again.outputs).toMatchObject({ key: "v1.1.0", "release-changed": "false" });
  });

  it("wraps unmarked CHANGELOG entries in the workspace, keeping the rest of the file", async () => {
    const repo = repoWithTags(["v1.0.0", "v1.1.0", "v1.2.0"]);
    const c = clock();
    const releases = timedReleases(c, []);
    const original = [
      "# Changelog",
      "",
      "## [Unreleased]",
      "",
      "- Pending",
      "",
      "## [v1.1.0] - 2026-02-01",
      "",
      "### Features",
      "",
      "- Export to CSV",
      "",
      "## [v1.0.0] - 2026-01-10",
      "",
      "- First release",
      "",
      "[v1.1.0]: https://github.com/acme/widgets/compare/v1.0.0...v1.1.0",
      "",
    ].join("\n");
    writeFileSync(join(repo.dir, "CHANGELOG.md"), original);
    const run = await adopt(
      { workspace: repo.dir, to: "", allTags: true },
      config({ outputs: { changelog: { enabled: true } } }),
      deps(repo, c, releases)
    );
    const text = readFileSync(join(repo.dir, "CHANGELOG.md"), "utf8");
    const blocks = findMarkedBlocks(text);
    expect(blocks.map((b) => [b.fields.key, b.fields.gen])).toEqual([
      ["v1.1.0", "adopted"],
      ["v1.0.0", "adopted"],
    ]);
    expect(blocks[0].inner).toBe("## [v1.1.0] - 2026-02-01\n\n### Features\n\n- Export to CSV");
    expect(blocks[1].inner).toBe("## [v1.0.0] - 2026-01-10\n\n- First release");
    // Text outside the entries is unchanged, and the link references stay outside the blocks.
    expect(text.startsWith("# Changelog\n\n## [Unreleased]\n\n- Pending\n\n")).toBe(true);
    expect(
      text.endsWith(
        "<!-- releaseray:end key=v1.0.0 persona=engineer -->\n\n[v1.1.0]: https://github.com/acme/widgets/compare/v1.0.0...v1.1.0\n"
      )
    ).toBe(true);
    expect(run.outputs["changelog-changed"]).toBe("true");
    expect(run.files).toEqual(["CHANGELOG.md"]);
    expect(run.summary).toContain("| `v1.2.0` | no release | no entry |");

    const target = {
      sink: "changelog" as const,
      exists: true,
      text,
      mode: "section" as const,
      onHumanEdit: "skip" as const,
      createIfMissing: true,
    };
    for (const key of ["v1.0.0", "v1.1.0"]) {
      expect(planSink(target, { key, persona: "engineer", gen: "1", force: false }).action).toBe(
        "noop"
      );
    }

    const again = await adopt(
      { workspace: repo.dir, to: "", allTags: true },
      config({ outputs: { changelog: { enabled: true } } }),
      deps(repo, c, releases)
    );
    expect(again.outputs["changelog-changed"]).toBe("false");
    expect(readFileSync(join(repo.dir, "CHANGELOG.md"), "utf8")).toBe(text);
  });

  it("exits 3 when the first write is refused and 7 when a later one is", async () => {
    const tags = ["v1.0.0", "v1.1.0"];
    const repo = repoWithTags(tags);
    const c = clock();
    const refused = Object.assign(new Error("Resource not accessible by integration"), {
      status: 403,
    });

    const none = timedReleases(
      c,
      tags.map((tag) => ({ tag, body: hostedBody(tag) }))
    );
    none.api.updateBody = async () => {
      throw refused;
    };
    const first = await failure(() =>
      adopt({ workspace: repo.dir, to: "", allTags: true }, config(), deps(repo, c, none))
    );
    expect(first.exitCode).toBe(3);
    expect(first.details.join("\n")).toMatch(/contents: write/);

    const some = timedReleases(
      c,
      tags.map((tag) => ({ tag, body: hostedBody(tag) }))
    );
    const update = some.api.updateBody;
    let calls = 0;
    some.api.updateBody = async (id, body) => {
      if (++calls === 2) throw refused;
      return update(id, body);
    };
    const later = await failure(() =>
      adopt({ workspace: repo.dir, to: "", allTags: true }, config(), deps(repo, c, some))
    );
    expect(later.exitCode).toBe(7);
    expect(later.message).toBe("Partial adopt: 1 release adopted before v1.0.0 failed");
  });

  it("exits 2 without a tag, with both to and all-tags, for an unknown tag, and on a shallow clone", async () => {
    const repo = repoWithTags(["v1.0.0"]);
    const c = clock();
    const releases = timedReleases(c, []);
    for (const request of [
      { to: "", allTags: false },
      { to: "HEAD", allTags: false },
      { to: "v1.0.0", allTags: true },
      { to: "v9.9.9", allTags: false },
    ]) {
      const error = await failure(() =>
        adopt({ workspace: repo.dir, ...request }, config(), deps(repo, c, releases))
      );
      expect(error.exitCode, JSON.stringify(request)).toBe(2);
    }
    const none = await failure(() =>
      adopt(
        { workspace: repo.dir, to: "", allTags: true },
        config({ range: { tagPattern: "release-*" } }),
        deps(repo, c, releases)
      )
    );
    expect(none.message).toMatch(/No tag matches range.tagPattern/);

    const shallow = createTestRepo();
    repos.push(shallow);
    shallow.commit("one", "2026-01-01");
    shallow.commit("two", "2026-01-02");
    const clone = mkdtempSync(join(tmpdir(), "releaseray-shallow-"));
    dirs.push(clone);
    execFileSync("git", ["clone", "-q", "--depth", "1", `file://${shallow.dir}`, clone]);
    const error = await failure(() =>
      adopt({ workspace: clone, to: "", allTags: true }, config(), {
        ...deps(repo, c, releases),
        git: createGit(clone),
      })
    );
    expect(error.exitCode).toBe(2);
    expect(error.details.join("\n")).toContain("fetch-depth: 0");
    expect(releases.reads()).toBe(0);
  });
});
